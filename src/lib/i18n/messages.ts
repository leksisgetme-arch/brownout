export const messages = { en, id } as const;

export function t(
	locale: Locale,
	key: MessageKey,
	vars?: Record<string, string | number>,
): string {
	const table: Record<MessageKey, string> = messages[locale];
	const template = table[key] ?? messages.en[key] ?? key;
	if (!vars) return template;
	return template.replace(/\{(\w+)\}/g, (match, name: string) =>
		name in vars ? String(vars[name]) : match,
	);
}

export function errorMessage(locale: Locale, code: string): string {
	const key = `error.${code}` as MessageKey;
	const table: Record<string, string> = messages[locale];
	return table[key] ?? messages[locale]["error.unknown"];
}
